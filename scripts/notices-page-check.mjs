// Real Chrome, real reading time. Run after building ui; uses only this worktree (NOTICES_PORT defaults to 4624).
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { ready, standInCore, openPage, sleep } from './headless.mjs';
import { uiServer } from './ui-server.mjs';
const unavailable = ready();
if (unavailable) { console.log(`SKIP notices-page-check: ${unavailable}`); process.exit(3); }
const modules = await uiServer();
const { lingerMs } = await modules.ssrLoadModule('/src/note-card.ts');
const { upFor } = await modules.ssrLoadModule('/src/notice-rules.ts');
await modules.close();
const thread = { id: 'T1', title: 'Garden', parent_id: null, status: 'open', last_point: '', touched_ms: Date.now(), tags: [], picture: null, dropped_by: '' };
const world = { threads: [thread], thoughts: [], active: 'T1', active_by: { you: 'T1' }, suggestions: [], actions: [], merged: {}, apps: [], apps_seeded: true, recaps: [] };
const note = (id, text) => ({ type: 'note_card', id, title: `Garden ${id}`, state: 'saved', live: true, message: 'Saved to Notes', sections: [{ title: 'Next steps', points: [{ text, who: '', decided: false, unfinished: false }] }] });
const port = Number(process.env.NOTICES_PORT ?? 4624);
const core = await standInCore(() => [{ type: 'snapshot', world }], { port });
let browser;
try {
  browser = await openPage('about:blank', { debugPort: port + 1 });
  const { page, evaluate, until } = browser;
  await page('Page.enable');
  await page('Page.addScriptToEvaluateOnNewDocument', { source: `localStorage.setItem('e2a2o.toured','1'); window.errors=[]; addEventListener('error',e=>{if(!e.message.startsWith('ResizeObserver loop')) errors.push(e.message)}); addEventListener('unhandledrejection',e=>errors.push(String(e.reason)));` });
  const check = async (expr, message, ms = 5000) => assert.ok(await until(expr, ms), message);
  const visit = async (path = '/?shell=2') => {
    await page('Page.navigate', { url: `http://127.0.0.1:${core.port}${path}` });
    await check(`!!document.querySelector('#type-a-thought')`, 'composer ready');
    await check(`document.querySelector('.app.shell') !== null`, 'map ready');
  };
  const type = async (text) => {
    await evaluate(`document.querySelector('#type-a-thought').focus()`);
    await page('Input.insertText', { text });
    await page('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 });
    await page('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 });
    await check(`document.querySelector('#type-a-thought').value === ''`, 'typed command consumed');
  };
  const hover = async (selector) => {
    const at = await evaluate(`(() => {const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`);
    await page('Input.dispatchMouseEvent', { type: 'mouseMoved', ...at });
  };
  const away = () => page('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 5, y: 5 });
  await visit();
  const short = note(1, 'Plant peas.');
  const long = note(2, 'Choose a sunny spot near the fence and prepare the soil before planting the peas, then water them gently and check each morning for new shoots.');
  assert.ok(lingerMs(long) > lingerMs(short), 'whole note length determines reading time');
  core.send({ ...short, state: "saving" }); core.send(long); core.send(short);
  await check(`document.querySelector('.note-card-title')?.textContent === 'Garden 1'`, 'first note stays first');
  await sleep(lingerMs(short) - 500);
  assert.equal(await evaluate(`document.querySelector('.note-card-title')?.textContent`), 'Garden 1', 'short note gets full reading time');
  await check(`document.querySelector('.note-card-title')?.textContent === 'Garden 2'`, 'next note follows', 4000);
  await sleep(700);
  await evaluate(`navigator.mediaDevices.getUserMedia = async () => {
    const ctx = new AudioContext(), tone = ctx.createOscillator(), out = ctx.createMediaStreamDestination();
    tone.connect(out); tone.start(); return out.stream;
  }`);
  const mic = await evaluate(`(() => {const r=document.querySelector('button.mic').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`);
  for (const type of ['mousePressed', 'mouseReleased']) await page('Input.dispatchMouseEvent', { type, ...mic, button: 'left', clickCount: 1 });
  await check(`document.querySelector('button.mic').getAttribute('aria-pressed') === 'true'`, 'synthetic microphone starts');
  core.send({ type: 'status', listening: true });
  core.send({ type: 'partial', text: 'I am still describing the garden' });
  await check(`document.body.textContent.includes('I am still describing the garden')`, 'live speech reaches the page');
  await sleep(700);
  await hover('.note-card');
  core.send({ type: 'change', change: { type: 'thread_retitled', thread_id: 'T1', was: 'Garden', title: 'Spring garden' } });
  core.send({ type: 'notice', message: 'Your seeds are ready.' });
  core.send({ type: 'correctable', for_ms: 8000, back_to: null });
  core.send({ type: 'change', change: { type: 'thought_added', thought: { id: 'speech', speaker: 'you', text: 'Water them tomorrow', point: 'Water them tomorrow', thread_id: 'T1', placed: true, unclear: '', complete: true, at_ms: Date.now(), place_ms: 1 } } });
  await sleep(1000);
  await sleep(lingerMs(long) + 200);
  assert.equal(await evaluate(`document.querySelector('.note-card-title')?.textContent`), 'Garden 2', 'hover and speech preserve long note');
  assert.equal(await evaluate(`!!document.querySelector('.map-change, .notice')`), false, 'later notices wait');
  writeFileSync('/private/tmp/e2a2o-r-notices.png', Buffer.from((await page('Page.captureScreenshot')).data, 'base64'));
  await away();
  await evaluate(`document.querySelector('.note-card-close').click()`);
  await check(`document.querySelector('.map-change')?.textContent.includes('Spring garden')`, 'map update next');
  await hover('.map-change');
  const mapText = await evaluate(`document.querySelector('.map-change').textContent`);
  await sleep(upFor(mapText) + 200);
  assert.ok(await evaluate(`!!document.querySelector('.map-change')`), 'map update holds on hover');
  await away();
  await evaluate(`document.querySelector('[aria-label="Dismiss map update"]').click()`);
  await check(`document.querySelector('.notice')?.textContent.includes('Your seeds are ready.')`, 'new notice follows once');
  await sleep(800);
  assert.equal(await evaluate(`!!document.querySelector('.map-change, .note-card')`), false, 'read cards never reappear');
  console.log('PASS reading time, hover, speech, and FIFO without flicker');

  // Command-delivery check only: this fixture does not run speech recognition.
  await type('stop showing this');
  await check(`!document.querySelector('.notice')`, 'typed stop dismisses current kind');
  core.send({ type: 'notice', message: 'Another seed update.' });
  await sleep(300);
  assert.equal(await evaluate(`!!document.querySelector('.notice')`), false, 'same kind suppressed');
  await visit();
  core.send({ type: 'notice', message: 'Still quiet after reload.' });
  await sleep(300);
  assert.equal(await evaluate(`!!document.querySelector('.notice')`), false, 'suppression survives reload');
  core.send(note(3, 'Pack seeds.'));
  await check(`!!document.querySelector('.note-card')`, 'other kinds remain enabled');
  core.send({ type: 'notice_control', show: false });
  await check(`!document.querySelector('.note-card')`, 'delivered stop dismisses note');
  await visit();
  core.send(note(4, 'These stay quiet.'));
  await sleep(300);
  assert.equal(await evaluate(`!!document.querySelector('.note-card')`), false, 'delivered suppression survives reload');
  core.send({ type: 'notice_control', show: true });
  core.send(note(5, 'Visible again.'));
  await check(`document.querySelector('.note-card-title')?.textContent === 'Garden 5'`, 'delivered restore enables notes');
  await type('stop showing this');
  await type('show those again');
  core.send(note(6, 'Typed restore works.'));
  await check(`document.querySelector('.note-card-title')?.textContent === 'Garden 6'`, 'typed restore enables notes');
  await evaluate(`document.querySelector('.note-card-close').click()`);
  core.send({ type: 'notice', message: 'Notices are back too.' });
  await check(`document.querySelector('.notice')?.textContent.includes('Notices are back too.')`, 'restore enables all muted kinds');
  assert.equal(core.heard.some(m => m.type === 'text' && /stop showing this|show those again/.test(m.text)), false, 'preferences never become thoughts');
  console.log('PASS typed and delivered suppression, restoration, and reload persistence');
  await evaluate(`document.querySelector('[aria-label="Dismiss notice"]').click()`);
  core.send({ type: 'notice', message: 'Same words, next turn.' });
  core.send({ type: 'notice', message: 'Same words, next turn.' });
  await check(`document.querySelector('.notice')?.textContent.includes('Same words, next turn.')`, 'repeated answers appear');
  await sleep(upFor('Same words, next turn.') + 400);
  assert.ok(await evaluate(`!!document.querySelector('.notice')`), 'second identical answer gets its own reading time');
  await check(`!document.querySelector('.notice')`, 'second identical answer expires too', upFor('Same words, next turn.') + 2000);
  console.log('PASS identical answers each get one reading turn');
  core.send(note(7, 'Read before sending.'));
  await check(`!!document.querySelector('.note-card')`, 'note precedes countdown');
  core.send({ type: 'send_card', id: 99, to: 'Test', text: 'Queued message', state: 'counting', in_ms: 15000, live: false, message: '' });
  await sleep(200);
  assert.equal(await evaluate(`!!document.querySelector('.send-card')`), false, 'countdown cannot bypass the queue');
  await type('stop showing this');
  await check(`!!document.querySelector('.send-card') && !document.querySelector('.note-card')`, 'mute applies to the visible note, then countdown advances');
  await type('stop showing this');
  await check(`!document.querySelector('.send-card')`, 'visible countdown kind can be silenced');
  await type('show those again');
  core.send({ type: 'apps_build', build: { id: 'orphan', request: 'Make a card', stage: 'composing', steps: ['Working'], draft: null, match_id: null, message: '', instead: '' } });
  await check(`!!document.querySelector('.dock-build')`, 'pending build displayed');
  core.drop();
  await check(`!document.querySelector('.dock-build')`, 'source removal retires the pending build');
  await check(`!document.querySelector('button.mic')?.disabled`, 'connection returned');
  core.send(note(7, 'New note with a reused id after restart.'));
  await check(`document.querySelector('.note-card')?.textContent.includes('New note with a reused id')`, 'reused note id displays after reconnect');
  console.log('PASS countdown queue, correct mute target, removed source, and restarted note ids');
  assert.deepEqual(await evaluate('errors'), [], 'no page errors');
} finally { await browser?.close(); core.close(); }
